/** @type {Record<string, any>} */
const ns = {};

/**
 * Retrieve a column by hash from a parsed database payload.
 * @param {{columns?: Column[]}|null|undefined} database
 * @param {string} colHash
 * @returns {Column|null}
 */
ns.getColumn = function (database, colHash) {
  if (!database || !Array.isArray(database.columns)) return null;
  return database.columns.find((col) => col?.col_hash === colHash) ?? null;
};

/**
 * Retrieve a column by hash and decode its raw values.
 * @param {{columns?: Column[]}|null|undefined} database Parsed database payload returned by parseColumns
 * @param {string} colHash Column hash to match
 * @param {number|null} [variantIndex=null] Optional variant index from col_vars
 * @returns {{ column: Column|null, variant: any|null, rawValues: any[] }}
 */
ns.getColumnValues = function (database, colHash, variantIndex = null) {
  const column = ns.getColumn(database, colHash);
  if (!column) {
    return { column: null, variant: null, rawValues: [] };
  }
  const hasVariantIndex = variantIndex !== null && variantIndex !== undefined;
  const variant = hasVariantIndex && Array.isArray(column.col_vars)
    ? column.col_vars[variantIndex] ?? null
    : null;
  const colType = variant?.col_type ?? column.col_type ?? 'q';
  let colSep = variant?.col_sep ?? column.col_sep;
  if (!colSep) colSep = colType === 'l' ? ';' : '';
  const colValues = variant?.col_values ?? column.col_values;
  const target = variant
    ? { ...variant, col_type: colType, col_sep: colSep, col_values: colValues }
    : { ...column, col_type: colType, col_sep: colSep, col_values: colValues };
  const rawValues = factors.decodeColumn(target) || [];
  return { column, variant, rawValues };
};

/**
 * Append a variant to the specified column, seeding the base variant when needed.
 * @param {{columns?: Column[]}|null|undefined} database Parsed database payload returned by parseColumns
 * @param {string} colHash Column hash to match
 * @param {any} newVariant Variant payload generated by variants.createVariant
 * @returns {any}
 */
ns.addVariant = function (database, colHash, newVariant) {
  if (!newVariant || typeof newVariant !== 'object') {
    throw new Error('Variant payload is required to add a variant.');
  }
  if (!database || !Array.isArray(database.columns)) {
    throw new Error('Invalid database payload; expected an object with columns.');
  }
  const column = ns.getColumn(database, colHash);
  if (!column) {
    throw new Error(`Column with hash ${colHash} not found in database.`);
  }
  if (!Array.isArray(column.col_vars) || column.col_vars.length === 0) {
    const colLabel = column.col_label ?? "Original";
    column.col_vars = [{
      var_label: colLabel,
      meta: { kind: 'original' }
    }];
  }
  column.col_vars.push(newVariant);
  return newVariant;
};

/**
 * Replace a variant at `editIndex` in the specified column and re-replay every
 * downstream variant (`editIndex + 1` and beyond) against the updated chain.
 *
 * The replay walks variants in order, reads each one's `meta.recipe`, and re-runs
 * `variants.createVariant` against the current `col_vars` state — so variants that
 * reference the edited one (via `sourceVarIndex`) get rebuilt with fresh data, and
 * variants that reference earlier (untouched) variants are re-derived equivalently.
 *
 * Graceful degradation: when a variant has no recipe or its replay throws, the old
 * variant is preserved and a warning is collected. `var_label` of the old variant
 * is always carried over to the replacement.
 *
 * Mutates `database` (consistent with `addVariant`). The `newVariant` argument is
 * not mutated.
 *
 * @param {{columns?: Column[]}|null|undefined} database Parsed database payload.
 * @param {string} colHash Column hash to match.
 * @param {number} editIndex Index in `col_vars` of the variant being replaced. Must be ≥ 1 (the base variant at index 0 is not editable).
 * @param {any} newVariant Variant payload generated by `variants.createVariant`.
 * @returns {{warnings: string[]}}
 */
ns.replaceVariantAt = function (database, colHash, editIndex, newVariant) {
  if (!newVariant || typeof newVariant !== 'object') {
    throw new Error('Variant payload is required to replace a variant.');
  }
  if (!database || !Array.isArray(database.columns)) {
    throw new Error('Invalid database payload; expected an object with columns.');
  }
  if (!Number.isInteger(editIndex) || editIndex < 1) {
    throw new Error(`Invalid editIndex ${editIndex}; must be an integer ≥ 1 (the base variant is not editable).`);
  }
  const column = ns.getColumn(database, colHash);
  if (!column) {
    throw new Error(`Column with hash ${colHash} not found in database.`);
  }
  if (!Array.isArray(column.col_vars) || editIndex >= column.col_vars.length) {
    throw new Error(`editIndex ${editIndex} out of bounds for col_vars length ${column.col_vars?.length ?? 0}.`);
  }

  /** @type {string[]} */
  const warnings = [];
  const oldDownstream = column.col_vars.slice(editIndex + 1);
  column.col_vars[editIndex] = newVariant;
  // Trim downstream — we'll rebuild them one by one against the updated chain.
  column.col_vars.length = editIndex + 1;

  oldDownstream.forEach((oldVar) => {
    const recipe = oldVar?.meta?.recipe;
    const label = oldVar?.var_label ?? 'unnamed';
    if (!recipe) {
      column.col_vars.push(oldVar);
      warnings.push(`Variant "${label}" has no stored recipe; kept previous data — may be stale.`);
      return;
    }
    try {
      const replayed = variants.createVariant(column, recipe);
      if (oldVar.var_label) replayed.var_label = oldVar.var_label;
      column.col_vars.push(replayed);
    } catch (err) {
      column.col_vars.push(oldVar);
      warnings.push(`Variant "${label}" recipe failed against the updated chain (${err?.message || err}); kept previous data.`);
    }
  });

  return { warnings };
};

/**
 * Remove the variant at `removeIndex` from `col_vars`, cascade-deleting any variants
 * that depend on it (directly or transitively via `sourceVarIndex`), and re-replay the
 * remaining downstream variants against the updated chain with adjusted indices.
 *
 * Cascade detection walks `col_vars` once in order, growing a set of "dependent" indices:
 * any variant whose `meta.recipe.sourceVarIndex` is in the set is added to the set.
 *
 * Preserved downstream variants are re-encoded via `variants.createVariant` with their
 * recipe's `sourceVarIndex` remapped to the new position. Variants with no recipe or
 * whose replay throws are silently kept in place (no warning) — only cascade removals
 * are reported via the `warnings` array, translated through `core/i18n`.
 *
 * Mutates `database`. Throws on invalid input (unknown column, removeIndex < 1 or out
 * of bounds — the base variant is not removable).
 *
 * @param {{columns?: Column[]}|null|undefined} database
 * @param {string} colHash
 * @param {number} removeIndex Index in `col_vars` of the variant to remove. Must be ≥ 1.
 * @param {{lang?: string}} [options]
 * @returns {{warnings: string[]}}
 */
ns.removeVariantAt = function (database, colHash, removeIndex, options = {}) {
  if (!database || !Array.isArray(database.columns)) {
    throw new Error('Invalid database payload; expected an object with columns.');
  }
  if (!Number.isInteger(removeIndex) || removeIndex < 1) {
    throw new Error(`Invalid removeIndex ${removeIndex}; must be an integer ≥ 1 (the base variant is not removable).`);
  }
  const column = ns.getColumn(database, colHash);
  if (!column) {
    throw new Error(`Column with hash ${colHash} not found in database.`);
  }
  if (!Array.isArray(column.col_vars) || removeIndex >= column.col_vars.length) {
    throw new Error(`removeIndex ${removeIndex} out of bounds for col_vars length ${column.col_vars?.length ?? 0}.`);
  }

  const lang = normalizeLanguage(options?.lang);
  const oldVars = column.col_vars;

  // Step 1: identify the set of variants to remove (target + transitive dependents).
  /** @type {Set<number>} */
  const dependentSet = new Set([removeIndex]);
  for (let i = removeIndex + 1; i < oldVars.length; i++) {
    const srcIdx = oldVars[i]?.meta?.recipe?.sourceVarIndex;
    if (Number.isInteger(srcIdx) && dependentSet.has(srcIdx)) {
      dependentSet.add(i);
    }
  }

  // Step 2: build old → new index remap for preserved variants.
  /** @type {Map<number, number>} */
  const indexMap = new Map();
  let newIdx = 0;
  for (let i = 0; i < oldVars.length; i++) {
    if (!dependentSet.has(i)) {
      indexMap.set(i, newIdx);
      newIdx += 1;
    }
  }

  // Step 3: pre-removeIndex variants reference indices < removeIndex (sourceVarIndex < self
  // by contract), all preserved with unchanged positions — copy intact, no replay needed.
  column.col_vars = oldVars.slice(0, removeIndex);

  // Step 4: re-replay each preserved variant after removeIndex, in order, with sourceVarIndex
  // remapped. Failures are silent (variant kept as-is, original col_values preserved).
  for (let i = removeIndex + 1; i < oldVars.length; i++) {
    if (dependentSet.has(i)) continue;
    const oldVar = oldVars[i];
    const recipe = oldVar?.meta?.recipe;
    if (!recipe) {
      column.col_vars.push(oldVar);
      continue;
    }
    const oldSrcIdx = recipe.sourceVarIndex;
    const remappedSrc = Number.isInteger(oldSrcIdx) ? indexMap.get(oldSrcIdx) : undefined;
    if (remappedSrc === undefined) {
      column.col_vars.push(oldVar);
      continue;
    }
    const adjustedRecipe = { ...recipe, sourceVarIndex: remappedSrc };
    try {
      const replayed = variants.createVariant(column, adjustedRecipe);
      if (oldVar.var_label) replayed.var_label = oldVar.var_label;
      column.col_vars.push(replayed);
    } catch {
      column.col_vars.push(oldVar);
    }
  }

  // Step 5: warnings — only for cascade-removed dependents (not the explicitly removed one).
  /** @type {string[]} */
  const warnings = [];
  Array.from(dependentSet)
    .sort((a, b) => a - b)
    .forEach((idx) => {
      if (idx === removeIndex) return;
      const label = oldVars[idx]?.var_label ?? `index ${idx}`;
      warnings.push(translate('variants.warnings.cascadeDeleted', lang, { label }));
    });

  return { warnings };
};

/**
 * Build row-wise objects from column-major raw_values.
 * @param {Column[]} columns
 * @returns {Array<Record<string, any>>}
 */
ns.getRowwiseData = function (columns) {
  if (!Array.isArray(columns)) return [];
  const n = Math.max(...columns.map(c => c.raw_values?.length || 0));
  const rows = [];
  for (let i = 0; i < n; i++) { const row = {}; columns.forEach(col => { row[col.col_hash] = col.raw_values?.[i] ?? null; }); rows.push(row); }
  return rows;
};

/**
 * Convert named-row objects into a 2D matrix following provided column order.
 * @param {string[]} columns
 * @param {Array<Record<string, any>>} rows
 * @returns {any[][]}
 */
ns.tabularRowsToMatrix = function (columns, rows) { return rows.map(row => columns.map(col => row[col])); };

/**
 * Frequency table for qualitative values.
 * @param {Array<string|null|undefined>} values
 * @param {(ctx:{count:number,percent:number,total:number})=>string=} formatFn
 * @param {{missing_label?:string, include_missing?:boolean, lang?:string}=} options
 * @param {{labels?: string[]|null}=} param3
 * @returns {TableLike}
 */
ns.summarize_q = function (values, formatFn = null, options = {}, { labels = null } = {}) {
  const freqMap = {}; let missingCount = 0; const total = values.length;
  const lang = normalizeLanguage(options?.lang);
  const missingLabel = options?.missing_label ?? getDefaultMissingLabel(lang);
  const includeMissing = options?.include_missing ?? true;
  const [variableHeader, descriptionHeader] = getTableHeaders(lang);
  values.forEach(val => { const v = val?.toString().trim(); if (!v) { missingCount++; return; } freqMap[v] = (freqMap[v] || 0) + 1; });
  const sortedLabels = labels ?? Object.keys(freqMap).sort();
  const rows = sortedLabels.map(label => { const count = freqMap[label] || 0; const percent = (count / total) * 100; const percentFormatted = formatNumberLocale(percent, 1, lang); const cell = formatFn ? formatFn({ count, percent, total }) : `${count} (${percentFormatted}%)`; return { [variableHeader]: label, [descriptionHeader]: cell }; });
  if (includeMissing && missingCount > 0) { const percent = (missingCount / total) * 100; const percentFormatted = formatNumberLocale(percent, 1, lang); const cell = formatFn ? formatFn({ count: missingCount, percent, total }) : `${missingCount} (${percentFormatted}%)`; rows.push({ [variableHeader]: missingLabel, [descriptionHeader]: cell }); }
  return { columns: [variableHeader, descriptionHeader], rows, summary: { total, total_is_full: true }, lang };
};

/**
 * Frequency table for list-like qualitative values (split by a separator).
 * @param {Array<string|null|undefined>} values
 * @param {string=} sep
 * @param {(ctx:{count:number,percent:number,total:number})=>string=} formatFn
 * @param {{missing_label?: string, include_missing?: boolean, lang?: string}=} options
 * @returns {TableLike}
 */
ns.summarize_l = function (values, sep = ';', formatFn = null, options = {}) {
  if (!Array.isArray(values)) return { columns: [], rows: [], summary: { total: 0, total_is_full: true } };
  const counts = {}; let missingCount = 0; const total = values.length;
  const lang = normalizeLanguage(options?.lang);
  const missingLabel = options?.missing_label ?? getDefaultMissingLabel(lang);
  const includeMissing = options?.include_missing ?? true;
  const [variableHeader, descriptionHeader] = getTableHeaders(lang);
  values.forEach(v => { if (!v?.trim()) { missingCount++; return; } const items = v.split(sep).map(s => s.trim()).filter(Boolean); if (items.length === 0) { missingCount++; return; } items.forEach(item => { counts[item] = (counts[item] || 0) + 1; }); });
  const rows = Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([level, count]) => { const percent = (count / total) * 100; const percentFormatted = formatNumberLocale(percent, 1, lang); const cell = formatFn ? formatFn({ count, percent, total }) : `${count} (${percentFormatted}%)`; return { [variableHeader]: level, [descriptionHeader]: cell }; });
  if (includeMissing && missingCount > 0) { const percent = (missingCount / total) * 100; const percentFormatted = formatNumberLocale(percent, 1, lang); const cell = formatFn ? formatFn({ count: missingCount, percent, total }) : `${missingCount} (${percentFormatted}%)`; rows.push({ [variableHeader]: missingLabel, [descriptionHeader]: cell }); }
  return { columns: [variableHeader, descriptionHeader], rows, summary: { total, total_is_full: true }, lang };
};

/**
 * Expand list-like predictors into binary yes/no columns and summarize against qualitative responses.
 * Returns one chi-square table per list item.
 * @param {Array<string|null|undefined>} listValues
 * @param {string[]} responseVals
 * @param {(ctx:{count:number,percent:number,rowTotal:number,colTotal:number})=>string=} formatFn
 * @param {{lang?:string}=} options
 * @param {{separator?:string,predictorLabel?:string|null,responseLabel?:string|null,lang?:string}=} meta
 * @returns {Array<{label:string,predictor_label?:string|null,predictor_label_stripped?:string|null,response_label?:string|null,table:TableLike}>}
 */
ns.summarize_l_q = function (listValues, responseVals, formatFn = null, options = {}, meta = {}) {
  const separator = meta?.separator ?? ';';
  const predictorLabel = meta?.predictorLabel ?? null;
  const responseLabel = meta?.responseLabel ?? null;
  const lang = normalizeLanguage(meta?.lang ?? options?.lang);
  const includePrefix = meta?.includePrefix ?? true;
  const cleanedPredictor = predictorLabel ? predictorLabel.replace(/[\s\p{P}]+$/u, '') : predictorLabel;
  const { columns: binaryColumns = {} } = numeric.decomposeListAsBinaryCols(listValues, separator, options);
  const results = [];
  Object.entries(binaryColumns).forEach(([label, binVals]) => {
    try {
      const table = contingency.summarize_q_q(binVals, responseVals, formatFn, options);
      const displayLabel = includePrefix && (cleanedPredictor || predictorLabel)
        ? `${cleanedPredictor || predictorLabel}: ${label}`
        : label;
      results.push({
        label,
        display_label: displayLabel,
        predictor_label: predictorLabel,
        predictor_label_stripped: cleanedPredictor,
        response_label: responseLabel,
        table
      });
    } catch (e) {
      const warnMessage = translate('warnings.summarizeFailure', lang, { label, context: predictorLabel ?? '' });
      console.warn(`${warnMessage}:`, e.message);
    }
  });
  return results;
};

/**
 * Profile B dispatcher: paired analysis across K ≥ 2 response columns (same individuals,
 * different momentos). Type-locked to the first response: all responses must share its type.
 * Currently supports numeric (paired t / Wilcoxon / Friedman) and binary qualitative
 * (McNemar / Cochran's Q). List responses and non-binary qualitative are rejected with
 * a translated warning surfaced via `table.warning`.
 *
 * @param {any[]} columns Resolved column objects (built by `runAnalysis`).
 * @param {Array<{col_hash:string, col_var_index?:number|null, col_label:string}>} responses
 * @param {Record<string,any>} options
 * @param {Set<string>} flagsUsed
 * @param {string} lang
 * @returns {{predictor:null, response:string|null, predictor_type:null, response_type:string|null, table:any}|null}
 */
ns.summarizePaired = function (columns, responses, options, flagsUsed, lang) {
  if (responses.length < 2) {
    flagsUsed.add('has_paired');
    return {
      predictor: null,
      response: responses[0]?.col_label || null,
      predictor_type: null,
      response_type: null,
      table: { warning: translate('warnings.pairedTooFewMomentos', lang) }
    };
  }
  // Cross-DB guard: paired analysis assumes same-individual row alignment, which only
  // holds within a single database. Cross-DB responses would produce silently bogus
  // pairings (rows truncated to min length, indices treated as same individual across DBs).
  const dbIds = new Set(responses.map((/** @type {any} */ r) => r.database_id));
  if (dbIds.size > 1) {
    flagsUsed.add('has_paired');
    return {
      predictor: null,
      response: responses[0]?.col_label || null,
      predictor_type: null,
      response_type: null,
      table: { warning: translate('warnings.pairedMultiDbNotAllowed', lang, {
        databases: [...dbIds].join(', ')
      }) }
    };
  }
  const resolvedCols = responses.map((r) =>
    columns.find((c) => c.col_hash === r.col_hash && c.col_var_index === (r.col_var_index ?? null))
      || columns.find((c) => c.col_hash === r.col_hash)
  );
  if (resolvedCols.some((c) => !c)) return null;
  /** @type {string[]} */
  const types = resolvedCols.map((c) => c.col_type);
  const firstType = types[0];
  // Type-lock: reject mixed responses.
  if (types.some((t) => t !== firstType)) {
    flagsUsed.add('has_paired');
    return {
      predictor: null,
      response: responses[0]?.col_label || null,
      predictor_type: null,
      response_type: firstType,
      table: { warning: translate('warnings.pairedMixedTypes', lang, { types: types.join(', ') }) }
    };
  }
  const labels = responses.map((r) => r.col_label);
  if (firstType === 'n') {
    flagsUsed.add('has_paired_n');
    const arrays = resolvedCols.map((c) => c.raw_values || []);
    const table = numeric.summarize_n_paired(arrays, labels, null, flagsUsed, { ...options, lang });
    return {
      predictor: null,
      response: labels.join(' × '),
      predictor_type: null,
      response_type: 'n',
      table
    };
  }
  if (firstType === 'q') {
    // Binary check: all responses must have ≤ 2 distinct non-empty levels.
    const levelSets = resolvedCols.map((c) => new Set((c.raw_values || []).map((v) => v?.toString().trim()).filter(Boolean)));
    const allBinary = levelSets.every((s) => s.size <= 2 && s.size >= 1);
    if (!allBinary) {
      flagsUsed.add('has_paired');
      const maxLevels = Math.max(...levelSets.map((s) => s.size));
      return {
        predictor: null,
        response: responses[0]?.col_label || null,
        predictor_type: null,
        response_type: 'q',
        table: { warning: translate('warnings.pairedNonBinaryQ', lang, { levels: maxLevels }) }
      };
    }
    // Use the union of observed levels as the binary pair.
    const unionLevels = [...new Set(levelSets.flatMap((s) => [...s]))].sort();
    if (unionLevels.length !== 2) {
      flagsUsed.add('has_paired');
      return {
        predictor: null,
        response: responses[0]?.col_label || null,
        predictor_type: null,
        response_type: 'q',
        table: { warning: translate('warnings.pairedNonBinaryQ', lang, { levels: unionLevels.length }) }
      };
    }
    flagsUsed.add('has_paired_q');
    const arrays = resolvedCols.map((c) => c.raw_values || []);
    const table = contingency.summarize_q_binary_paired(arrays, labels, null, { ...options, lang }, { levels: unionLevels });
    return {
      predictor: null,
      response: labels.join(' × '),
      predictor_type: null,
      response_type: 'q',
      table
    };
  }
  if (firstType === 'l') {
    flagsUsed.add('has_paired');
    return {
      predictor: null,
      response: responses[0]?.col_label || null,
      predictor_type: null,
      response_type: 'l',
      table: { warning: translate('warnings.pairedListNotSupported', lang) }
    };
  }
  return null;
};

/**
 * Cross-tabulation of a qualitative predictor vs a list response.
 *
 * The list response is decomposed into binary (Yes/No) columns per item, and each binary
 * column is treated as the response in a `summarize_q_q` call against the qualitative
 * predictor. Mirror of `summarize_l_q` with predictor/response axes swapped.
 *
 * @param {string[]} predictorVals Qualitative predictor values (one per row).
 * @param {string[]} responseVals List response values (semi-colon-separated by default).
 * @param {((ctx:{count:number,percent:number,rowTotal:number,colTotal:number})=>string)|null} [formatFn]
 * @param {Record<string,any>} [options]
 * @param {{separator?:string, predictorLabel?:string|null, responseLabel?:string|null, lang?:string, includePrefix?:boolean}} [meta]
 * @returns {Array<{label:string, display_label:string, predictor_label:string|null, response_label:string|null, response_label_stripped:string|null, table:any}>}
 */
ns.summarize_q_l = function (predictorVals, responseVals, formatFn = null, options = {}, meta = {}) {
  const separator = meta?.separator ?? ';';
  const predictorLabel = meta?.predictorLabel ?? null;
  const responseLabel = meta?.responseLabel ?? null;
  const lang = normalizeLanguage(meta?.lang ?? options?.lang);
  const includePrefix = meta?.includePrefix ?? true;
  const cleanedResponse = responseLabel ? responseLabel.replace(/[\s\p{P}]+$/u, '') : responseLabel;
  const { columns: binaryColumns = {} } = numeric.decomposeListAsBinaryCols(responseVals, separator, options);
  const results = [];
  Object.entries(binaryColumns).forEach(([label, binVals]) => {
    try {
      const table = contingency.summarize_q_q(predictorVals, binVals, formatFn ?? undefined, options);
      const displayLabel = includePrefix && (cleanedResponse || responseLabel)
        ? `${cleanedResponse || responseLabel}: ${label}`
        : label;
      results.push({
        label,
        display_label: displayLabel,
        predictor_label: predictorLabel,
        response_label: responseLabel,
        response_label_stripped: cleanedResponse,
        table
      });
    } catch (e) {
      const warnMessage = translate('warnings.summarizeFailure', lang, { label, context: responseLabel ?? '' });
      console.warn(`${warnMessage}:`, e.message);
    }
  });
  return results;
};

/**
 * Cross-tabulation of a list predictor vs a list response with explicit subset selection.
 *
 * Both columns are decomposed into binary (Yes/No) item columns. For each pair
 * `(predItem ∈ predSubset, respItem ∈ respSubset)`, a 2×2 contingency table is built via
 * `contingency.summarize_q_q`. Items in the subsets that do not occur in the data are
 * skipped silently.
 *
 * The subset gate is enforced by the dispatcher in `summarizePredictors` — without
 * both subsets, the dispatch emits a warning instead of calling this helper.
 *
 * @param {string[]} predictorVals List predictor values.
 * @param {string[]} responseVals List response values.
 * @param {((ctx:{count:number,percent:number,rowTotal:number,colTotal:number})=>string)|null} [formatFn]
 * @param {Record<string,any>} [options]
 * @param {{predictorSep?:string, responseSep?:string, predictorLabel?:string|null, responseLabel?:string|null, predSubset?:string[], respSubset?:string[], lang?:string, includePrefix?:boolean}} [meta]
 * @returns {Array<{predictor_item:string, response_item:string, display_predictor:string, display_response:string, table:any}>}
 */
ns.summarize_l_l = function (predictorVals, responseVals, formatFn = null, options = {}, meta = {}) {
  const predictorSep = meta?.predictorSep ?? ';';
  const responseSep = meta?.responseSep ?? ';';
  const predictorLabel = meta?.predictorLabel ?? null;
  const responseLabel = meta?.responseLabel ?? null;
  const lang = normalizeLanguage(meta?.lang ?? options?.lang);
  const includePrefix = meta?.includePrefix ?? true;
  const predSubset = Array.isArray(meta?.predSubset) ? meta.predSubset.filter(Boolean) : [];
  const respSubset = Array.isArray(meta?.respSubset) ? meta.respSubset.filter(Boolean) : [];
  if (!predSubset.length || !respSubset.length) return [];

  const cleanedPredictor = predictorLabel ? predictorLabel.replace(/[\s\p{P}]+$/u, '') : predictorLabel;
  const cleanedResponse = responseLabel ? responseLabel.replace(/[\s\p{P}]+$/u, '') : responseLabel;

  const { columns: predBinary = {} } = numeric.decomposeListAsBinaryCols(predictorVals, predictorSep, options);
  const { columns: respBinary = {} } = numeric.decomposeListAsBinaryCols(responseVals, responseSep, options);

  const results = [];
  for (const pItem of predSubset) {
    if (!predBinary[pItem]) continue;
    for (const rItem of respSubset) {
      if (!respBinary[rItem]) continue;
      try {
        const table = contingency.summarize_q_q(predBinary[pItem], respBinary[rItem], formatFn ?? undefined, options);
        const displayPred = includePrefix && (cleanedPredictor || predictorLabel)
          ? `${cleanedPredictor || predictorLabel}: ${pItem}`
          : pItem;
        const displayResp = includePrefix && (cleanedResponse || responseLabel)
          ? `${cleanedResponse || responseLabel}: ${rItem}`
          : rItem;
        results.push({
          predictor_item: pItem,
          response_item: rItem,
          display_predictor: displayPred,
          display_response: displayResp,
          table
        });
      } catch (e) {
        const warnMessage = translate('warnings.summarizeFailure', lang, { label: `${pItem} × ${rItem}`, context: predictorLabel ?? '' });
        console.warn(`${warnMessage}:`, e.message);
      }
    }
  }
  return results;
};

/**
 * Compare a numeric response across binary "presence" groups derived from a list predictor.
 *
 * The list predictor is decomposed into binary (Yes/No) columns per item, and each item
 * becomes the grouping variable in a `summarize_n_q` call against the numeric response.
 * Mirror of `summarize_l_q` for the `l × n` case.
 *
 * @param {string[]} predictorVals List predictor values.
 * @param {string[]} responseVals Numeric response values.
 * @param {Function|null} [formatFn]
 * @param {Set<string>|null} [flagsUsed]
 * @param {Record<string,any>} [options]
 * @param {{separator?:string, predictorLabel?:string|null, responseLabel?:string|null, lang?:string, includePrefix?:boolean}} [meta]
 * @returns {Array<{label:string, display_label:string, predictor_label:string|null, predictor_label_stripped:string|null, response_label:string|null, table:any}>}
 */
ns.summarize_l_n = function (predictorVals, responseVals, formatFn = null, flagsUsed = null, options = {}, meta = {}) {
  const separator = meta?.separator ?? ';';
  const predictorLabel = meta?.predictorLabel ?? null;
  const responseLabel = meta?.responseLabel ?? null;
  const lang = normalizeLanguage(meta?.lang ?? options?.lang);
  const includePrefix = meta?.includePrefix ?? true;
  const cleanedPredictor = predictorLabel ? predictorLabel.replace(/[\s\p{P}]+$/u, '') : predictorLabel;
  const { columns: binaryColumns = {} } = numeric.decomposeListAsBinaryCols(predictorVals, separator, options);
  const results = [];
  Object.entries(binaryColumns).forEach(([label, binVals]) => {
    try {
      // summarize_n_q signature is (numericVals, groupingVals). The binary Yes/No column
      // is the grouping variable; the numeric response is summarized within each group.
      const table = numeric.summarize_n_q(responseVals, binVals, formatFn, flagsUsed, options);
      const displayLabel = includePrefix && (cleanedPredictor || predictorLabel)
        ? `${cleanedPredictor || predictorLabel}: ${label}`
        : label;
      results.push({
        label,
        display_label: displayLabel,
        predictor_label: predictorLabel,
        predictor_label_stripped: cleanedPredictor,
        response_label: responseLabel,
        table
      });
    } catch (e) {
      const warnMessage = translate('warnings.summarizeFailure', lang, { label, context: predictorLabel ?? '' });
      console.warn(`${warnMessage}:`, e.message);
    }
  });
  return results;
};

